// Production FE against the temporary --serve-ui server.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const base = process.env.REACT_UI_URL || 'http://127.0.0.1:5077/app/'
;(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
  try {
    const page = await browser.newPage(), errors = []
    page.on('pageerror', e => errors.push(e.message))
    await page.goto(base)
    await page.getByLabel('Email', { exact: true }).fill('admin@benchconsole.local')
    await page.getByLabel('Mật khẩu', { exact: true }).fill('Admin@12345')
    await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
    await page.locator('.app-shell').waitFor()
    await page.goto(base + 'files?category=tai-lieu')
    const name = 'Doc UI ' + Date.now(), payload = Buffer.from('Original document bytes')
    await page.getByRole('button', { name: 'Tải lên', exact: true }).click()
    let dialog = page.getByRole('dialog')
    await dialog.getByLabel('Tên hiển thị', { exact: false }).fill(name)
    for (const [label, value] of [['Chương trình', 'FRS'], ['Category', 'Body'], ['Function', 'Door Lock'], ['Type tài liệu', 'Specification']])
      await dialog.getByLabel(label, { exact: true }).fill(value)
    await dialog.locator('input[type=file]').setInputFiles({ name: 'spec.txt', mimeType: 'text/plain', buffer: payload })
    await dialog.getByRole('button', { name: 'Tải lên', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    let row = page.getByRole('row').filter({ hasText: name })
    await row.waitFor()
    for (const value of ['FRS', 'Body', 'Door Lock', 'Specification']) await row.getByText(value, { exact: true }).waitFor()
    await page.getByLabel('Lọc Chương trình', { exact: true }).locator('option[value="FRS"]').waitFor({ state: 'attached' })
    await page.getByLabel('Lọc Chương trình', { exact: true }).selectOption('FRS')
    await page.waitForURL(/documentProgram=FRS/)
    await page.reload()
    await page.getByLabel('Lọc Chương trình', { exact: true }).locator('option[value="FRS"]').waitFor({ state: 'attached' })
    assert.equal(await page.getByLabel('Lọc Chương trình', { exact: true }).inputValue(), 'FRS')
    await row.waitFor()
    await row.getByRole('button', { name: 'Thông tin / sửa', exact: true }).click()
    dialog = page.getByRole('dialog')
    assert.equal(await dialog.getByLabel('Chương trình', { exact: true }).inputValue(), 'FRS')
    await dialog.getByLabel('Chương trình', { exact: true }).fill('VF6')
    await dialog.getByLabel('Function', { exact: true }).fill('Window Control')
    await dialog.getByLabel('Category', { exact: true }).fill('')
    await dialog.getByLabel('Type tài liệu', { exact: true }).fill('Guide')
    await dialog.getByRole('button', { name: 'Lưu', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    await row.waitFor({ state: 'hidden' }) // Still filtered by FRS.
    await page.getByLabel('Lọc Chương trình', { exact: true }).selectOption('')
    await row.waitFor()
    for (const value of ['VF6', 'Window Control', 'Guide']) await row.getByText(value, { exact: true }).waitFor()
    await row.getByRole('button', { name: 'Thông tin / sửa', exact: true }).click()
    dialog = page.getByRole('dialog')
    assert.equal(await dialog.getByLabel('Category', { exact: true }).inputValue(), '')
    await dialog.getByRole('button', { name: 'Huỷ', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    const downloaded = page.waitForEvent('download')
    await row.getByRole('button', { name: 'Tải về', exact: true }).click()
    assert.deepEqual(await fs.readFile(await (await downloaded).path()), payload)
    await page.getByPlaceholder('Tìm tên / chương trình / Category / Function / Type').fill('Window Control')
    await row.waitFor()
    assert.deepEqual(errors, [])
    console.log('OK: Tài liệu upload bốn trường, lọc/reload, sửa metadata, gợi ý tên, tìm Function và download đúng bytes.')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
